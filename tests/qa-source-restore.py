#!/usr/bin/env python3
"""Verify a source-snapshot ZIP and rehearse a clean restore in a temp directory.

Operates only on the source archive generated by create_source_snapshot.py.
Never touches the browser's IndexedDB, operating Netlify site or private files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import tempfile
import zipfile


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def verify(source_zip: Path) -> dict:
    expected_sha_file = Path(str(source_zip) + ".sha256")
    expected_sha = expected_sha_file.read_text(encoding="utf-8").split()[0]
    if not re.fullmatch(r"[0-9a-f]{64}", expected_sha):
        raise ValueError("Invalid external ZIP digest")
    actual_sha = sha256(source_zip.read_bytes())
    if expected_sha != actual_sha:
        raise ValueError("Whole ZIP SHA-256 mismatch")

    with zipfile.ZipFile(source_zip) as z:
        if z.testzip() is not None:
            raise ValueError("ZIP CRC verification failed")
        infos = z.infolist()
        names = [x.filename for x in infos]
        if len(set(names)) != len(names):
            raise ValueError("Duplicate ZIP paths")
        for info in infos:
            name = PurePosixPath(info.filename)
            if (name.is_absolute() or ".." in name.parts or
                    not info.filename.startswith("snapshot/") or
                    any(part in ("", ".") for part in name.parts)):
                raise ValueError("Unsafe ZIP entry path")
            if ((info.external_attr >> 16) & 0o170000) == 0o120000:
                raise ValueError("Symbolic link in ZIP")

        manifest = json.loads(z.read("snapshot/MANIFEST.json"))
        if manifest.get("schema") != "source-snapshot-v1":
            raise ValueError("Unsupported manifest")
        if manifest.get("project") != "uri-wrong-answer-qa":
            raise ValueError("Unexpected project")
        expected = manifest.get("files")
        if not isinstance(expected, list) or not expected:
            raise ValueError("No source files in manifest")
        if manifest.get("source_file_count") != len(expected):
            raise ValueError("Manifest count mismatch")

        registered = set()
        with tempfile.TemporaryDirectory(prefix="qa-source-restore-") as tmp:
            root = Path(tmp)
            for entry in expected:
                name = entry["path"]
                if (not isinstance(name, str) or name.startswith("/") or
                        ".." in PurePosixPath(name).parts or
                        not name or name in registered):
                    raise ValueError("Invalid source path")
                registered.add(name)
                file_path = "snapshot/source/" + name
                data = z.read(file_path)
                if len(data) != entry["size"] or sha256(data) != entry["sha256"]:
                    raise ValueError("Restored file mismatches source digest: " + name)
                dest = root / name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(data)
                if sha256(dest.read_bytes()) != entry["sha256"]:
                    raise ValueError("Restored disk contents changed")
            required = {"index.html", "check.html", "README.md", "tests/qa-e2e.mjs",
                "scripts/qa-family-gateway.mjs", "scripts/qa-inapp-sync-bridge.mjs",
                "scripts/qa-family-merge-preflight.mjs",
                "db/qa39_family_rls.sql", "scripts/qa39-tenant-store.mjs",
                "tests/qa39-postgres-tenant.mjs",
                "docs/QA39_G15_PostgreSQL_가족격리_실운영인계_v0.1.md",
                "docs/QA39_G16_학습효과_사전등록_검토본_v0.2.md",
                "scripts/qa40-oidc-resolver.mjs", "tests/qa40-oidc-postgres.mjs",
                "docs/QA40_G15_서명JWT_보호자RLS_연동검증_v0.1.md",
                "scripts/qa41-signed-family-http.mjs", "tests/qa41-http-api.mjs",
                "docs/QA41_G15_HTTP_JWT_RLS_통합검증_v1.0.md"}
            if not required.issubset(registered):
                raise ValueError("Missing important app/test files")
            index = (root / "index.html").read_text(encoding="utf-8")
            if "<html lang=\"ko\">" not in index or 'id="page-home"' not in index:
                raise ValueError("Restored index does not look like QA app")
            js = sorted([*(root / "tests").glob("*.mjs"), *(root / "scripts").glob("*.mjs")])
            if not js:
                raise ValueError("No restored test scripts")
            for path in js:
                subprocess.run(["node", "--check", str(path)],check=True,
                               stdout=subprocess.DEVNULL,stderr=subprocess.PIPE)
            source_set = {"snapshot/source/" + n for n in registered}
            others = {"snapshot/MANIFEST.json", "snapshot/SHA256SUMS.txt", "snapshot/RECOVERY.txt"}
            if set(names) != source_set | others:
                raise ValueError("Extra or unlisted file in archive")
            checksum_entries = z.read("snapshot/SHA256SUMS.txt").decode("utf-8").splitlines()
            expected_checksums = [entry["sha256"] + "  snapshot/source/" + entry["path"] for entry in expected]
            # Packager prefixes the checksum entries relative to snapshot/, not root.
            normalized = [x.replace("  snapshot/source/", "  source/", 1) for x in expected_checksums]
            if checksum_entries != normalized:
                raise ValueError("SHA256SUMS and manifest disagree")

            return {
                "status":"PASS","source_files":len(registered),"js_scripts_checked":len(js),
                "source_commit":manifest.get("source_commit"),"archive_sha256":actual_sha,
                "restore_target":"temporary-directory","browser_data_included":False
            }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", default="source-snapshot-output")
    args = parser.parse_args()
    sources = list(Path(args.output_dir).glob("uri-wrong-answer-qa_source_*.zip"))
    if len(sources) != 1:
        raise ValueError("Expected exactly one source archive, got " + str(len(sources)))
    print("QA_RESTORE_RESULT=" + json.dumps(verify(sources[0]), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, RuntimeError, KeyError, subprocess.CalledProcessError,
            zipfile.BadZipFile, json.JSONDecodeError) as exc:
        print("QA_RESTORE_RESULT=" + json.dumps(
            {"status": "FAIL", "error": str(exc)}, ensure_ascii=False),file=sys.stderr)
        sys.exit(1)
