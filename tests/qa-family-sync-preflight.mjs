import assert from 'node:assert/strict';
import {checkBackup,previewMerge,signSynthetic,SyncPreflightError} from '../scripts/qa-family-merge-preflight.mjs';
const profile={grade:'3',nickname:'SYNTHETIC-ONLY'};
const row=id=>({id,problemText:'qa synthetic example',hasPhoto:false,practiceHistory:[],generalRetryHistory:[]});
const mk=(rows,photos={})=>signSynthetic({format:'uriaimath-offline-backup-v02',profile:structuredClone(profile),records:structuredClone(rows),photos:structuredClone(photos)});
let count=0;
const pass=s=>{count++;console.log('PASS G15 PREP',s)};
const local=mk([row('sample-a')]),remote=mk([row('sample-b')]);
const oldL=structuredClone(local),oldR=structuredClone(remote);
const plan=previewMerge(local,remote);
assert.deepEqual([plan.proposedRecords,plan.newRecords,plan.canAutoApply],[2,1,false]);
assert.equal(plan.dataDelivered,false);assert.equal(plan.networkUsed,false);
assert.deepEqual(local,oldL);assert.deepEqual(remote,oldR);
pass('서로 다른 두 기기 합성기록 사전검사로만 합집합 계획; 자동 적용·네트워크·원본 변경 없음');
assert.equal(previewMerge(local,mk([row('sample-a')])).identicalRecords,1);
pass('동일한 레코드 ID의 완전 동일 자료는 중복으로 표시');
function rejects(fn,code){assert.throws(fn,e=>e instanceof SyncPreflightError&&e.code===code)}
const changed=row('sample-a');changed.problemText='different attempt';
rejects(()=>previewMerge(local,mk([changed])),'RECORD_CONFLICT');
pass('같은 ID 다른 본문은 유실 위험으로 병합 중지');
const invalid=structuredClone(local);invalid.records[0].problemText='tampered';
rejects(()=>previewMerge(invalid,remote),'CHECKSUM');
pass('백업 무결성 값 불일치 차단');
const nickname=mk([row('sample-b')]);nickname.profile.nickname='DIFFERENT';signSynthetic(nickname);
rejects(()=>previewMerge(local,nickname),'PROFILE_CONFLICT');
pass('서로 다른 가족 프로필 간 자동 병합 차단');
const badPhoto=row('photo');badPhoto.hasPhoto=true;
rejects(()=>previewMerge(local,mk([badPhoto])),'ORPHAN');
pass('사진이 빠진 데이터 차단');
const photos=mk([{...row('photo'),hasPhoto:true}],{'photo':{mime:'image/png',data:'synthetic-no-real-children'}});
assert.equal(checkBackup(photos).photoCount,1);
pass('사진 참조가 온전히 들어 있는 합성 자료만 통과');
const photoAlter=mk([{...row('photo'),hasPhoto:true}],{'photo':{mime:'image/png',data:'different'}});
rejects(()=>previewMerge(photos,photoAlter),'PHOTO_CONFLICT');
pass('같은 ID의 사진 바이트 충돌 시 자동 결합 중지');
rejects(()=>checkBackup(mk([row('same'),row('same')])),'DUPLICATE');
rejects(()=>checkBackup(mk(Array.from({length:501},(_,i)=>row('qa-'+i)))),'COUNT');
pass('중복 레코드·501개 한도 차단');
console.log('QA_G15_READINESS_RESULT='+JSON.stringify({status:'PASS',checks:count,implementation:'LOCAL PREFLIGHT ONLY',
 actualFamilyAuthentication:false,actualCloudSync:false,productionReady:false}));
